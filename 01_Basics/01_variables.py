# Lesson 01: Variables and Data Types
# Variables are containers for storing data values.

# Strings (Text)
first_name = "Dexter"
food = "pizza"
email = "dexter123@example.com"

# Integers (Whole Numbers)
age = 25
quantity = 4

# Floats (Decimal Numbers)
price = 10.99
gpa = 3.85

# Booleans (True / False)
for_sale = True
is_online = False

# Displaying variables
print(f"Hello, my name is {first_name} and I love {food}.")
print(f"You ordered {quantity} items at ${price} each.")
print(f"Account email: {email}")

if for_sale:
    print("Status: That item is currently for sale.")
else:
    print("Status: That item is not available.")
