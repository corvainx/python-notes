# Lesson 05: Built-in Math Functions

x = 3.14159
y = -4
z = 5

print(f"Original values: x={x}, y={y}, z={z}")

# round() rounds to nearest integer or specified decimal places
print(f"round(x): {round(x)}")
print(f"round(x, 2): {round(x, 2)}")

# abs() returns the absolute value (distance from zero)
print(f"abs(y): {abs(y)}")

# pow(base, exp) calculates base raised to the exponent
print(f"pow(2, 3): {pow(2, 3)}")

# max() and min() find extreme values
print(f"max(x, y, z): {max(x, y, z)}")
print(f"min(x, y, z): {min(x, y, z)}")
