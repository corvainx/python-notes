# Lesson 01: Function Basics and Invocation
# Functions encapsulate reusable blocks of logic.

def greet_user(name, age):
    """Prints a formatted greeting card for a user."""
    print(f"Happy birthday to {name}!")
    print(f"You are now {age} years old.")
    print("Wishing you an incredible year ahead!\n")

greet_user("Alice", 23)
greet_user("Bob", 25)
greet_user("Dexter", 30)
